"""Writes site/js/gamedata.js from a gamedata.json (game tables decoded from the Steam build).
    python site/tools/make_gamedata.py path/to/gamedata.json"""
import json
import sys
from pathlib import Path

d = json.loads(Path(sys.argv[1]).read_text())
out = {'source': d['source'], 'items': d['items'], 'buildings': d['buildings'], 'recipes': d['recipes']}
for b in out['buildings'].values():
    b.pop('cost', None)
js = ('// Game tables (buildings, recipes, items) extracted from the Steam build. Generated by tools/make_gamedata.py.\n'
      'export const GAMEDATA = ' + json.dumps(out, separators=(',', ':')) + ';\n')
(Path(__file__).resolve().parent.parent / 'js' / 'gamedata.js').write_text(js)
